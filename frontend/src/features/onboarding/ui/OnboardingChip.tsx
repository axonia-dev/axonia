import type { CSSProperties } from "react";
import { useRef } from "react";
import {
  Button as AriaButton,
  DialogTrigger,
  Group,
  Popover,
} from "react-aria-components";

import { useCloseOnboarding } from "@/features/onboarding/api/use-onboarding";
import {
  type OnboardingPath,
  visitedCount,
} from "@/features/onboarding/domain/onboarding";

import { OnboardingPanel } from "./OnboardingPanel";

// react-aria sizes the popover to the space left on screen and this is the cap that measurement
// is taken as the minimum of. Set to clear the longest path there is - six steps, each with its
// description - so the common case scrolls not at all; the list inside carries the matching
// `overflow-y-auto` for the viewport too short to grant it.
const PANEL_MAX_HEIGHT = 560;

const panelPopoverClass =
  "flex w-[min(21rem,calc(100vw-1.5rem))] flex-col overflow-hidden rounded-2xl border border-border-strong bg-surface shadow-lg outline-none transition data-[entering]:opacity-0 data-[entering]:-translate-y-1 data-[exiting]:opacity-0 data-[exiting]:-translate-y-1 motion-reduce:transition-none";

/** The shared shape of both chips: the open one and the one that marks the finish. Kept here so
 *  the finish chip cannot drift a pixel from the control it replaces for its few seconds. */
export const chipClass =
  "inline-flex cursor-pointer items-center gap-2 rounded-full border py-1 pr-3 pl-1 text-xs font-semibold shadow-sm transition-colors outline-none focus-visible:ring-focus-ring focus-visible:ring-offset-background focus-visible:ring-2 focus-visible:ring-offset-2";

/** The progress belongs in the trigger's name, not only on its face: the ring is decorative
 *  markup a screen reader is told to skip. */
function triggerLabel(visited: number, total: number): string {
  return `Getting started, ${visited} of ${total} seen`;
}

function progressAngle(visited: number, total: number): string {
  const fraction = total === 0 ? 0 : visited / total;
  return `${fraction * 360}deg`;
}

/** The gradient reads a CSS custom property set inline on this element; a Tailwind class name
 *  assembled from a variable is never generated by the compiler, so the class itself stays
 *  static and only the property's value changes per render.
 *
 *  The hue is `var(--primary)`, not `var(--color-primary)`: `@theme inline` resolves the
 *  `--color-*` aliases once at the root, so an alias ignores every override below it - a
 *  community's accent included. See the guard in `src/test/theme-variables.test.ts`. */
function ProgressRing({
  visited,
  total,
}: Readonly<{ visited: number; total: number }>) {
  return (
    <span
      aria-hidden
      style={{ "--p": progressAngle(visited, total) } as CSSProperties}
      className="relative inline-grid size-[22px] shrink-0 place-items-center rounded-full [background:conic-gradient(var(--primary)_var(--p),var(--surface-sunken)_0)]"
    >
      <span className="bg-surface text-foreground relative z-10 inline-flex size-4 items-center justify-center rounded-full text-[8px] font-bold">
        {`${visited}/${total}`}
      </span>
    </span>
  );
}

/**
 * The shell's way into {@link OnboardingPanel}: a pill carrying a progress ring that opens the
 * step list. Follows `NotificationBell` - a `Group` anchors the popover to the whole control
 * rather than the button alone, since the ring is decorative and must not itself become the
 * anchor box.
 *
 * The word beside the ring is dropped below `sm`, where the top bar has no room for it; the
 * button's accessible name carries it either way.
 *
 * `OnboardingAffordance` decides whether this renders at all and supplies `path`; this
 * component owns only the popover and the dismiss wiring.
 */
export function OnboardingChip({ path }: Readonly<{ path: OnboardingPath }>) {
  const total = path.steps.length;
  const visited = visitedCount(path);
  const closeOnboarding = useCloseOnboarding();
  const triggerRef = useRef<HTMLDivElement>(null);

  return (
    <DialogTrigger>
      <Group
        role="presentation"
        ref={triggerRef}
        className="relative inline-flex flex-none"
      >
        <AriaButton
          aria-label={triggerLabel(visited, total)}
          className={`${chipClass} border-border-strong bg-surface text-foreground hover:bg-surface-sunken`}
        >
          <ProgressRing visited={visited} total={total} />
          <span className="hidden sm:inline">Getting started</span>
        </AriaButton>
      </Group>
      <Popover
        triggerRef={triggerRef}
        placement="bottom end"
        maxHeight={PANEL_MAX_HEIGHT}
        className={panelPopoverClass}
      >
        <OnboardingPanel
          path={path}
          onDismiss={() => closeOnboarding.mutate()}
        />
      </Popover>
    </DialogTrigger>
  );
}
