import { Check, ChevronRight } from "lucide-react";
import { useContext } from "react";
import {
  Dialog,
  Heading,
  OverlayTriggerStateContext,
} from "react-aria-components";
import { Link } from "react-router-dom";

import type {
  OnboardingPath,
  OnboardingStep,
} from "@/features/onboarding/domain/onboarding";
import { visitedCount } from "@/features/onboarding/domain/onboarding";
import { cn } from "@/lib/cn";

import { STEP_LABELS, stepDescription } from "./step-labels";

interface Props {
  path: OnboardingPath;
  onDismiss: () => void;
}

/** The panel says what the path is for, which is not the same sentence for the two variants: one
 *  person is building a community, the other is finding their way into one already running. */
const PANEL_TITLES: Record<OnboardingPath["variant"], string> = {
  ORGANIZER: "Get the community going",
  MEMBER: "The way in",
};

type TickState = "done" | "now" | "later";

// Spelled out per state rather than assembled: a class name built from a variable is never
// generated by Tailwind's scanner.
const TICK_CLASS: Record<TickState, string> = {
  done: "border-success bg-success text-success-foreground",
  now: "border-primary border-2 ring-[3px] ring-primary/15 bg-surface",
  later: "border-border-strong bg-surface",
};

function closeOverlay(overlay: { close: () => void } | null): void {
  if (overlay !== null) overlay.close();
}

function Tick({ state }: Readonly<{ state: TickState }>) {
  return (
    <span
      aria-hidden
      className={cn(
        "mt-px grid size-[19px] flex-none place-items-center rounded-full border",
        TICK_CLASS[state],
      )}
    >
      {state === "done" && <Check size={11} strokeWidth={3.4} />}
    </span>
  );
}

function StepText({ step }: Readonly<{ step: OnboardingStep }>) {
  const description = stepDescription(step);
  return (
    <span className="min-w-0">
      <span className="block text-[13.5px] leading-snug font-semibold">
        {STEP_LABELS[step.key]}
      </span>
      {description !== null && (
        <span className="text-muted-foreground mt-0.5 block text-xs leading-normal">
          {description}
        </span>
      )}
    </span>
  );
}

/** The step already seen: struck through, no link, and no description - the line saying what is
 *  kept there has done its work once the person has been. */
function VisitedRow({ step }: Readonly<{ step: OnboardingStep }>) {
  return (
    <li className="flex items-start gap-2.5 px-2.5 py-2">
      <Tick state="done" />
      <span className="text-muted-foreground block text-[13.5px] leading-snug font-medium line-through">
        {STEP_LABELS[step.key]}
      </span>
      <span className="sr-only">Done.</span>
    </li>
  );
}

function OpenRow({
  step,
  isNext,
  onNavigate,
}: Readonly<{
  step: OnboardingStep;
  isNext: boolean;
  onNavigate: () => void;
}>) {
  return (
    <li>
      <Link
        to={step.route}
        onClick={onNavigate}
        className="hover:bg-surface-sunken focus-visible:ring-focus-ring flex items-start gap-2.5 rounded-md px-2.5 py-2 outline-none focus-visible:ring-2 focus-visible:ring-inset"
      >
        <Tick state={isNext ? "now" : "later"} />
        <StepText step={step} />
        {isNext && (
          <span
            aria-hidden
            className="text-primary ml-auto flex flex-none items-center self-center text-xs font-semibold"
          >
            Open
            <ChevronRight size={13} />
          </span>
        )}
      </Link>
    </li>
  );
}

/** How far along the path is, drawn. Decorative: the count above it says the same thing in words,
 *  so a screen reader is told to skip this rather than read a second progress control. */
function ProgressBar({
  seen,
  total,
}: Readonly<{ seen: number; total: number }>) {
  const percent = total === 0 ? 0 : Math.round((seen / total) * 100);
  return (
    <span
      aria-hidden
      className="bg-surface-sunken mt-3 block h-1 overflow-hidden rounded-full"
    >
      <span
        className="from-primary to-primary/60 block h-full rounded-full bg-gradient-to-r transition-[width] duration-500"
        style={{ width: `${percent}%` }}
      />
    </span>
  );
}

/**
 * Lists the steps of one onboarding path and offers a final, unconfirmed way to hide it.
 * Rendered inside {@link OnboardingChip}'s popover; takes `path` and `onDismiss` as props rather
 * than reading the query itself, so it stays a pure view over whatever state its caller holds.
 *
 * Only the first unvisited step wears the primary marker and the Open affordance: the path is an
 * order, and a panel that invited six openings at once would say it is a menu instead.
 *
 * The server closes a path in the same write that marks its last step visited, so this panel
 * never has an open path with every step visited to render. Marking the finish is
 * `OnboardingAffordance`'s job, not this panel's.
 */
export function OnboardingPanel({ path, onDismiss }: Readonly<Props>) {
  const overlay = useContext(OverlayTriggerStateContext);
  const onNavigate = () => closeOverlay(overlay);
  const seen = visitedCount(path);
  const nextKey = path.steps.find((step) => !step.visited)?.key;

  return (
    <Dialog className="flex min-h-0 flex-col outline-none">
      <div className="px-4 pt-3.5 pb-1">
        <Heading
          slot="title"
          className="font-display text-foreground text-[15px] leading-tight font-semibold"
        >
          {PANEL_TITLES[path.variant]}
        </Heading>
        <p className="text-muted-foreground mt-1 text-xs">
          {`${seen} of ${path.steps.length} seen`}
        </p>
        <ProgressBar seen={seen} total={path.steps.length} />
      </div>

      <div className="relative min-h-0 flex-1 overflow-y-auto overscroll-contain p-1.5">
        <ul>
          {path.steps.map((step) =>
            step.visited ? (
              <VisitedRow key={step.key} step={step} />
            ) : (
              <OpenRow
                key={step.key}
                step={step}
                isNext={step.key === nextKey}
                onNavigate={onNavigate}
              />
            ),
          )}
        </ul>
      </div>

      <button
        type="button"
        onClick={onDismiss}
        aria-label="Hide the getting-started steps"
        className="border-border text-muted-foreground hover:text-foreground w-full cursor-pointer border-t py-2.5 text-center text-xs font-medium transition-colors"
      >
        Hide this
      </button>
    </Dialog>
  );
}
