-- How a held session felt: each attendee's own answer, or one import of answers gathered elsewhere.
CREATE TABLE public.session_feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    session_id bigint NOT NULL REFERENCES public.community_session(id),
    user_id character varying(255) NOT NULL,
    enjoyed smallint NOT NULL CHECK (enjoyed BETWEEN 1 AND 10),
    learned smallint NOT NULL CHECK (learned BETWEEN 1 AND 10),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    version bigint NOT NULL,
    CONSTRAINT uq_session_feedback_organization_session_user UNIQUE (organization_id, session_id, user_id)
);

CREATE INDEX idx_session_feedback_session_id ON public.session_feedback (session_id);

ALTER TABLE public.session_feedback ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.session_feedback
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

CREATE TABLE public.session_feedback_import (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    session_id bigint NOT NULL REFERENCES public.community_session(id),
    scale smallint NOT NULL CHECK (scale IN (5, 10)),
    source character varying(80) NOT NULL,
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT uq_session_feedback_import_organization_session UNIQUE (organization_id, session_id)
);

CREATE INDEX idx_session_feedback_import_session_id ON public.session_feedback_import (session_id);

ALTER TABLE public.session_feedback_import ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.session_feedback_import
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

CREATE TABLE public.session_feedback_import_answer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    import_id bigint NOT NULL REFERENCES public.session_feedback_import(id) ON DELETE CASCADE,
    enjoyed smallint CHECK (enjoyed BETWEEN 1 AND 10),
    learned smallint CHECK (learned BETWEEN 1 AND 10),
    CONSTRAINT session_feedback_import_answer_has_a_value CHECK (enjoyed IS NOT NULL OR learned IS NOT NULL)
);

CREATE INDEX idx_session_feedback_import_answer_import_id ON public.session_feedback_import_answer (import_id);

ALTER TABLE public.session_feedback_import_answer ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.session_feedback_import_answer
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));
