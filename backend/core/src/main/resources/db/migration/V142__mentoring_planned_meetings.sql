-- A pairing plans any number of meetings, each on its own day with the topics it will take up, instead of holding a
-- single next meeting. A meeting is held once a note of its pairing names its day.

CREATE TABLE public.mentoring_meeting (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    pairing_id bigint NOT NULL REFERENCES public.mentoring_pairing(id) ON DELETE CASCADE,
    meeting_on date NOT NULL,
    planned_by character varying(255),
    planned_at timestamp with time zone NOT NULL,
    CONSTRAINT mentoring_meeting_day_key UNIQUE (pairing_id, meeting_on)
);

CREATE INDEX idx_mentoring_meeting_org_day ON public.mentoring_meeting (organization_id, meeting_on);

CREATE TABLE public.mentoring_meeting_topic (
    organization_id character varying(255) NOT NULL,
    meeting_id bigint NOT NULL REFERENCES public.mentoring_meeting(id) ON DELETE CASCADE,
    topic_id bigint NOT NULL REFERENCES public.mentoring_topic(id) ON DELETE CASCADE,
    CONSTRAINT mentoring_meeting_topic_pkey PRIMARY KEY (meeting_id, topic_id)
);

CREATE INDEX idx_mentoring_meeting_topic_topic_id ON public.mentoring_meeting_topic (topic_id);

ALTER TABLE public.mentoring_meeting ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.mentoring_meeting
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

ALTER TABLE public.mentoring_meeting_topic ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.mentoring_meeting_topic
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

INSERT INTO public.mentoring_meeting (organization_id, pairing_id, meeting_on, planned_by, planned_at)
SELECT organization_id, id, next_meeting_on, next_meeting_set_by, next_meeting_set_at
  FROM public.mentoring_pairing
 WHERE next_meeting_on IS NOT NULL;
