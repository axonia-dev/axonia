CREATE TABLE public.mentoring_pointer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    pairing_id bigint NOT NULL REFERENCES public.mentoring_pairing(id) ON DELETE CASCADE,
    topic_id bigint REFERENCES public.mentoring_topic(id) ON DELETE CASCADE,
    note_id bigint REFERENCES public.mentoring_note(id) ON DELETE CASCADE,
    kind character varying(8) NOT NULL CHECK (kind IN ('SESSION', 'TALK', 'ARTIFACT', 'MEMBER', 'LINK')),
    target_id bigint,
    target_user_id character varying(255),
    url character varying(2000),
    created_at timestamp with time zone NOT NULL,
    CONSTRAINT mentoring_pointer_has_one_owner CHECK (num_nonnulls(topic_id, note_id) = 1)
);

CREATE INDEX idx_mentoring_pointer_pairing_id ON public.mentoring_pointer (pairing_id);

ALTER TABLE public.mentoring_pointer ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.mentoring_pointer
