-- A mentor who stays: who offers or seeks mentoring in a community, the proposals between two members, the
-- pairings they become, and what a pairing keeps (topics, notes, pointers, the mentee's parting words).
-- Instants are written by the application. No default, so SQL never stamps them.

CREATE TABLE public.mentoring_availability (
    organization_id character varying(255) NOT NULL,
    community_id bigint NOT NULL,
    user_id character varying(255) NOT NULL,
    taking_mentees boolean NOT NULL,
    mentee_limit smallint CHECK (mentee_limit BETWEEN 1 AND 10),
    looking_for_mentor boolean NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT mentoring_availability_pkey PRIMARY KEY (organization_id, community_id, user_id)
);

ALTER TABLE public.mentoring_availability ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.mentoring_availability
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

CREATE TABLE public.mentoring_proposal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    community_id bigint NOT NULL,
    mentor_user_id character varying(255) NOT NULL,
    mentee_user_id character varying(255) NOT NULL,
    proposed_by character varying(8) NOT NULL CHECK (proposed_by IN ('MENTOR', 'MENTEE')),
    topics character varying(80)[] NOT NULL,
    message character varying(500) NOT NULL,
    status character varying(10) NOT NULL CHECK (status IN ('OPEN', 'ACCEPTED', 'DECLINED', 'WITHDRAWN')),
    created_at timestamp with time zone NOT NULL,
    answered_at timestamp with time zone
);

CREATE INDEX idx_mentoring_proposal_mentor ON public.mentoring_proposal (organization_id, mentor_user_id);

CREATE INDEX idx_mentoring_proposal_mentee ON public.mentoring_proposal (organization_id, mentee_user_id);

ALTER TABLE public.mentoring_proposal ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.mentoring_proposal
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

-- Either user id is null once erasure has cleared that side of the pairing.
CREATE TABLE public.mentoring_pairing (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    community_id bigint NOT NULL,
    mentor_user_id character varying(255),
    mentee_user_id character varying(255),
    started_at timestamp with time zone NOT NULL,
    ended_at timestamp with time zone,
    end_reason character varying(12) CHECK (end_reason IN ('MENTOR', 'MENTEE', 'LEFT', 'DEACTIVATED')),
    words_asked_at timestamp with time zone
);

CREATE UNIQUE INDEX uq_mentoring_pairing_ongoing
    ON public.mentoring_pairing (organization_id, community_id, mentor_user_id, mentee_user_id)
    WHERE ended_at IS NULL;

CREATE INDEX idx_mentoring_pairing_mentor ON public.mentoring_pairing (organization_id, mentor_user_id);

CREATE INDEX idx_mentoring_pairing_mentee ON public.mentoring_pairing (organization_id, mentee_user_id);

ALTER TABLE public.mentoring_pairing ENABLE ROW LEVEL SECURITY;

CREATE POLICY organization_isolation ON public.mentoring_pairing
    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

CREATE TABLE public.mentoring_topic (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    pairing_id bigint NOT NULL REFERENCES public.mentoring_pairing(id) ON DELETE CASCADE,
    label character varying(80) NOT NULL,
    area character varying(80),
    state character varying(9) NOT NULL CHECK (state IN ('ONGOING', 'LONG_TERM', 'DONE')),
    "position" integer NOT NULL,
    created_at timestamp with time zone NOT NULL
);

CREATE INDEX idx_mentoring_topic_pairing_id ON public.mentoring_topic (pairing_id);

ALTER TABLE public.mentoring_topic ENABLE ROW LEVEL SECURITY;

