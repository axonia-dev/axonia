    USING (((organization_id)::text = current_setting('app.current_org'::text, true)))
    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

CREATE TABLE public.mentoring_note (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id character varying(255) NOT NULL,
    pairing_id bigint NOT NULL REFERENCES public.mentoring_pairing(id) ON DELETE CASCADE,
    author_user_id character varying(255) NOT NULL,
    body character varying(2000) NOT NULL,
    next_meeting_on date,
    written_at timestamp with time zone NOT NULL,
