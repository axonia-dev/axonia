    WITH CHECK (((organization_id)::text = current_setting('app.current_org'::text, true)));

-- The author is the pairing's mentee and the reader its mentor, so the row has no user column of its own.
CREATE TABLE public.mentoring_words (
    pairing_id bigint PRIMARY KEY REFERENCES public.mentoring_pairing(id) ON DELETE CASCADE,
    organization_id character varying(255) NOT NULL,
    body character varying(1000) NOT NULL,
    written_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone
);

ALTER TABLE public.mentoring_words ENABLE ROW LEVEL SECURITY;

